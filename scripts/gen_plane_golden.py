def emit_ints(lines, label, values, stride=16):
    lines.append("  %s:" % label)
    for start in range(0, len(values), stride):
        lines.append("  Data.l " +
                     ",".join(str(value) for value in values[start:start + stride]))
    lines.append("")


def emit_quads(lines, label, values, stride=8):
    lines.append("  %s:" % label)
    for start in range(0, len(values), stride):
        lines.append("  Data.q " +
                     ",".join(str(unsigned32(value)) for value in values[start:start + stride]))
    lines.append("")


def emit_bytes(lines, label, values, stride=32):
    lines.append("  %s:" % label)
    for start in range(0, len(values), stride):
        lines.append("  Data.b " +
                     ",".join(str(value) for value in values[start:start + stride]))
    lines.append("")


