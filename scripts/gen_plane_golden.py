"""
DoomPB - independent M4-01 visplane/flat/zlight golden generator.

Provenance and independence: the wall-only pixel planes, ordered visibility spans
and M3-05 render-plan numeric fields are generated by the already independent
gen_wall_texture_golden.py oracle, which itself reads only numeric trig tables
from pinned ../doom-original/linuxdoom-1.10/tables.c (commit
a77dfb96cb91780ca334d0d4cfd86957558007e0). This script then adds a separate
integer-only plane oracle for r_plane.c R_ClearPlanes/R_FindPlane/R_CheckPlane/
R_MakeSpans/R_MapPlane/R_DrawPlanes and r_draw.c R_DrawSpan, plus r_main.c
yslope/distscale/base scale and R_InitLightTables zlight[16][128]. It overlays
those independently computed floor/ceiling pixels onto the independent wall-only
frames for two wholly original synthetic scenes.

PI01: one sector, floor FLOOR1/h0/l160, ceiling CEIL1/h128/l160, one solid
TEXMID wall; view (0,0,angle0,viewz=41 units). No sky.

PI02: two sectors and TEXMID/TEXUP/TEXLO wall textures; front sector0 floor
FLOOR1/h0/l160, sky ceiling F_SKY1/h128/l160; back sector1 floor FLOOR2/h32/l96,
CEIL2/h96/l96; a solid wall and a two-sided portal with upper/lower/masked middle.
The sky visplane is normalized/collected but deferred; all its bands/pixels stay
background. Repeated floor-plane CheckPlane merges/splits across the wall spans.

Never from production output: expected yslope/distscale/base-scale rows,
zlight map levels, MapPlane row parameters/cache order, spot addresses, plane
find/check/mark/span counters, per-row spans/pixels, full 64,000 palette bytes and
FNV-1a64 hashes are computed by this Python oracle. The wall pixel half comes from
the separate already-independent M3-06 oracle; no Doom pixels/WAD bytes stored.
Totally synthetic deterministic data; regeneration twice is byte-identical.

Production and tests never execute Python.
"""
import argparse
import importlib.util
import os

MASK32 = 0xFFFFFFFF
SIGN32 = 0x80000000
FRACBITS = 16
FRACUNIT = 1 << FRACBITS
FINEANGLES = 8192
ANGLETOFINESHIFT = 19
FINEMASK = 8191
ANG90 = 0x40000000
VIEWWIDTH = 320
VIEWHEIGHT = 200
CENTERY = 100
CENTERXFIXED = 160 * FRACUNIT
PROJECTIONFIXED = CENTERXFIXED
HEIGHTBITS = 12
HEIGHTUNIT = 1 << HEIGHTBITS
LIGHTLEVELS = 16
LIGHTSEGSHIFT = 4
MAXLIGHTZ = 128
LIGHTZSHIFT = 20
LIGHTSCALESHIFT = 12
NUMCOLORMAPS = 32
DISTMAP = 2
SCREENWIDTH = VIEWWIDTH
FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211

SYNTH_FLATS = {
    # Namespace order from wall_texture_support.pbi: F_START then these flats.
    "FLOOR1": (0, 45), "FLOOR2": (1, 46), "CEIL1": (2, 47),
    "CEIL2": (3, 48), "F_SKY1": (4, 80),
}
SKYFLATNUM = SYNTH_FLATS["F_SKY1"][0]
SYNTH_COLORMAP_BASE = 17
SYNTH_COLORMAP_STEP = 9


def unsigned32(value):
    return value & MASK32


def signed32(value):
    low = value & MASK32
    if low >= SIGN32:
        return low - (1 << 32)
    return low


def lowadd(a, b):
    return signed32(unsigned32(a) + unsigned32(b))


def lowsub(a, b):
    return signed32(unsigned32(a) - unsigned32(b))


def lowneg(a):
    return signed32(-unsigned32(a))


def fixed_mul(a, b):
    return signed32(signed32(a) * signed32(b) >> FRACBITS)


def fixed_div(a, b):
    a = signed32(a)
    b = signed32(b)
    if (abs(a) >> 14) >= abs(b):
        return -2147483648 if (a < 0) != (b < 0) else 2147483647
    numerator = a * FRACUNIT
    magnitude = abs(numerator) // abs(b)
    if (numerator < 0) != (b < 0):
        magnitude = -magnitude
    return signed32(magnitude)


def trunc_div(numerator, denominator):
    if numerator == 0:
        return 0
    magnitude = abs(numerator) // abs(denominator)
    if (numerator < 0) != (denominator < 0):
        return -magnitude
    return magnitude


def load_module(filename, module_name):
    script_dir = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(script_dir, filename)
    spec = importlib.util.spec_from_file_location(module_name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def same_keyset(items):
    return sorted(items) == sorted(set(items))


def cosine(sine, index):
    """Doom finecosine alias: sine[FINEANGLES/4 + index] without FINEMASK wrap.

    The source exposes finecosine as a pointer at the sine table's second quarter;
    a valid fine index 0..8191 plus that offset stays inside the 10,240-entry table.
    Wrapping with FINEMASK would silently change output where the alias crosses the
    quarter boundary, as observed at distscale column 268.
    """
    return sine[index + FINEANGLES // 4]


def yslope_table():
    rows = []
    numerator = (SCREENWIDTH // 2) * FRACUNIT
    for row in range(VIEWHEIGHT):
        dy = abs(((row - CENTERY) << FRACBITS) + (FRACUNIT // 2))
        rows.append(fixed_div(numerator, dy))
    return rows


def distscale_table(inverse, sine):
    scales = []
    for screen_x in range(VIEWWIDTH):
        raw = unsigned32(inverse[screen_x])
        index = unsigned32(raw >> ANGLETOFINESHIFT) & FINEMASK
        magnitude = abs(cosine(sine, index))
        scales.append(fixed_div(FRACUNIT, magnitude))
    return scales


def zlight_table():
    levels = [[0] * MAXLIGHTZ for _ in range(LIGHTLEVELS)]
    numerator = (SCREENWIDTH // 2) * FRACUNIT
    for light_level in range(LIGHTLEVELS):
        startmap = ((LIGHTLEVELS - 1 - light_level) * 2) * NUMCOLORMAPS // LIGHTLEVELS
        for distance_index in range(MAXLIGHTZ):
            denominator = (distance_index + 1) << LIGHTZSHIFT
            scale = fixed_div(numerator, denominator)
            scaled = scale >> LIGHTSCALESHIFT
            level = startmap - scaled // DISTMAP
            if level < 0:
                level = 0
            if level >= NUMCOLORMAPS:
                level = NUMCOLORMAPS - 1
            levels[light_level][distance_index] = level
    return levels


def base_scales(viewangle, sine):
    angle = unsigned32(viewangle - ANG90)
    index = unsigned32(angle >> ANGLETOFINESHIFT) & FINEMASK
    xscale = fixed_div(cosine(sine, index), CENTERXFIXED)
    yscale = lowneg(fixed_div(sine[index], CENTERXFIXED))
    return xscale, yscale


def flatname_index(name):
    if name not in SYNTH_FLATS:
        raise ValueError("unnamed synthetic flat %r" % name)
    return SYNTH_FLATS[name][0]


def flatname_pixel(name):
    if name not in SYNTH_FLATS:
        raise ValueError("unnamed synthetic flat %r" % name)
    return SYNTH_FLATS[name][1]


def flat_pixel_by_index(index):
    for name, (flat_index, pixel) in SYNTH_FLATS.items():
        if flat_index == index:
            return pixel
    raise ValueError("unknown synthetic flat index %d" % index)


def colormap_value(texel, map_index):
    return (texel + SYNTH_COLORMAP_BASE + map_index * SYNTH_COLORMAP_STEP) & 255


class PlaneState:
    """Independent visplane records and exact Find/Check/sentinel semantics."""

    def __init__(self, sky_flatnum):
        self.sky_flatnum = sky_flatnum
        self.records = []
        self.spanstart = [0] * VIEWHEIGHT
        self.find_calls = 0
        self.find_reuse = 0
        self.find_create = 0
        self.check_calls = 0
        self.check_merges = 0
        self.check_splits = 0
        self.new_planes = []

    def _new_record(self, height, picnum, lightlevel, minx, maxx):
        record = {
            "Height": height, "FlatPic": picnum, "LightLevel": lightlevel,
            "Sky": 1 if picnum == self.sky_flatnum else 0,
            "MinX": minx, "MaxX": maxx,
            "Top": [255] * (VIEWWIDTH + 2),
            "Bottom": [0] * (VIEWWIDTH + 2),
        }
        self.records.append(record)
        self.new_planes.append(len(self.records) - 1)
        return record

    def find(self, height, picnum, lightlevel):
        if picnum == self.sky_flatnum:
            height = 0
            lightlevel = 0
        self.find_calls += 1
        for index, record in enumerate(self.records):
            if (height == record["Height"] and picnum == record["FlatPic"] and
                    lightlevel == record["LightLevel"]):
                self.find_reuse += 1
                return index
        self.find_create += 1
        self._new_record(height, picnum, lightlevel, VIEWWIDTH, -1)
        return len(self.records) - 1

    def check(self, old_index, start, stop):
        record = self.records[old_index]
        if start < record["MinX"]:
            intrl, unionl = record["MinX"], start
        else:
            unionl, intrl = record["MinX"], start
        if stop > record["MaxX"]:
            intrh, unionh = record["MaxX"], stop
        else:
            unionh, intrh = record["MaxX"], stop
        found = 0
        if intrl <= intrh:
            for x in range(intrl, intrh + 1):
                if record["Top"][x + 1] != 255:
                    found = 1
                    break
        self.check_calls += 1
        if not found:
            record["MinX"] = unionl
            record["MaxX"] = unionh
            self.check_merges += 1
            return old_index
        self.check_splits += 1
        new = self._new_record(record["Height"], record["FlatPic"],
                               record["LightLevel"], start, stop)
        return len(self.records) - 1

    def mark_ceiling(self, index, x, ceilingclip, floorclip, yl):
        record = self.records[index]
        top = ceilingclip + 1
        bottom = yl - 1
        if bottom >= floorclip:
            bottom = floorclip - 1
        if top <= bottom:
            record["Top"][x + 1] = top
            record["Bottom"][x + 1] = bottom
            return 1
        return 0

    def mark_floor(self, index, x, ceilingclip, floorclip, yh):
        record = self.records[index]
        top = yh + 1
        bottom = floorclip - 1
        if top <= ceilingclip:
            top = ceilingclip + 1
        if top <= bottom:
            record["Top"][x + 1] = top
            record["Bottom"][x + 1] = bottom
            return 1
        return 0

    def has_bands(self, index):
        record = self.records[index]
        for x in range(VIEWWIDTH):
            if record["Top"][x + 1] != 255:
                return 1
        return 0

    def top_sentinel(self, index, x):
        self.records[index]["Top"][x + 1] = 255


def wall_clip_coverage(scene, plans):
    """Independent wall tier painted-cell coverage from the same plans/clip."""
    coverage = [0] * (VIEWWIDTH * VIEWHEIGHT)
    clipped_ranges = []
    ceilingclip = [-1] * VIEWWIDTH
    floorclip = [VIEWHEIGHT] * VIEWWIDTH
    for plan in plans:
        pixhigh = plan["PixHigh"]
        pixlow = plan["PixLow"]
        for column in range(plan["FirstX"], plan["LastX"] + 1):
            ceilclip = ceilingclip[column]
            floorclip_current = floorclip[column]
            yl = lowadd(plan["TopFrac"], HEIGHTUNIT - 1) >> HEIGHTBITS
            if yl < ceilclip + 1:
                yl = ceilclip + 1
            yh = plan["BottomFrac"] >> HEIGHTBITS
            if yh >= floorclip_current:
                yh = floorclip_current - 1
            painted = []
            if plan["MiddleTier"]:
                painted.append((yl, yh))
                ceilingclip[column] = VIEWHEIGHT
                floorclip[column] = -1
            else:
                if plan["TopTier"]:
                    mid = pixhigh >> HEIGHTBITS
                    pixhigh = lowadd(pixhigh, plan["PixHighStep"])
                    if mid >= floorclip_current:
                        mid = floorclip_current - 1
                    if mid >= yl:
                        painted.append((yl, mid))
                        ceilingclip[column] = mid
                    else:
                        ceilingclip[column] = yl - 1
                elif plan["MarkCeiling"]:
                    ceilingclip[column] = yl - 1
                if plan["BottomTier"]:
                    mid = lowadd(pixlow, HEIGHTUNIT - 1) >> HEIGHTBITS
                    pixlow = lowadd(pixlow, plan["PixLowStep"])
                    if mid <= ceilclip:
                        mid = ceilclip + 1
                    if mid <= yh:
                        painted.append((mid, yh))
                        floorclip[column] = mid
                    else:
                        floorclip[column] = yh + 1
                elif plan["MarkFloor"]:
                    floorclip[column] = yh + 1
            for low, high in painted:
                if low <= high:
                    for row in range(low, high + 1):
                        if row < 0 or row >= VIEWHEIGHT:
                            raise ValueError("wall painted row out of frame")
                        coverage[row * VIEWWIDTH + column] = 1
                    clipped_ranges.append((column, low, high))
    return coverage, clipped_ranges, ceilingclip, floorclip


def plane_capture(scene, plans):
    """Independent r_segs.c plane marks and CheckPlane chronology."""
    viewz = signed32(scene["view"][3])
    state = PlaneState(SKYFLATNUM)
    sectors = scene["sectors"]
    front = sectors[plans[0]["FrontSector"]]
    floor_fixed = signed32(front["floor"] << FRACBITS)
    ceiling_fixed = signed32(front["ceiling"] << FRACBITS)
    floor_pic = flatname_index(front["floorpic"])
    ceiling_pic = flatname_index(front["ceilingpic"])
    floor_plane = -1
    ceiling_plane = -1
    floor_eligible = ceiling_eligible = 0
    if floor_fixed < viewz:
        floor_eligible = 1
        floor_plane = state.find(floor_fixed, floor_pic, front["light"])
    if ceiling_fixed > viewz or ceiling_pic == SKYFLATNUM:
        ceiling_eligible = 1
        ceiling_plane = state.find(ceiling_fixed, ceiling_pic, front["light"])
    ceiling_handle = ceiling_plane
    floor_handle = floor_plane
    ceilingclip = [-1] * VIEWWIDTH
    floorclip = [VIEWHEIGHT] * VIEWWIDTH
    mark_ceiling_columns = 0
    mark_floor_columns = 0
    mark_ceiling_bands = 0
    mark_floor_bands = 0
    span_events = []
    for plan_index, plan in enumerate(plans):
        first = plan["FirstX"]
        last = plan["LastX"]
        ceiling_before = ceiling_handle
        floor_before = floor_handle
        ceiling_checks = floor_checks = 0
        ceiling_merges = ceiling_splits = 0
        floor_merges = floor_splits = 0
        if plan["MarkCeiling"]:
            merges_before = state.check_merges
            splits_before = state.check_splits
            ceiling_handle = state.check(ceiling_handle, first, last)
            ceiling_checks = 1
            if state.check_merges > merges_before:
                ceiling_merges = 1
            if state.check_splits > splits_before:
                ceiling_splits = 1
        if plan["MarkFloor"]:
            merges_before = state.check_merges
            splits_before = state.check_splits
            floor_handle = state.check(floor_handle, first, last)
            floor_checks = 1
            if state.check_merges > merges_before:
                floor_merges = 1
            if state.check_splits > splits_before:
                floor_splits = 1
        bands_ceiling = bands_floor = 0
        scale = plan["Scale1"]
        topfrac = plan["TopFrac"]
        bottomfrac = plan["BottomFrac"]
        pixhigh = plan["PixHigh"]
        pixlow = plan["PixLow"]
        for column in range(first, last + 1):
            ceilclip = ceilingclip[column]
            floorclip_current = floorclip[column]
            yl = lowadd(topfrac, HEIGHTUNIT - 1) >> HEIGHTBITS
            if yl < ceilclip + 1:
                yl = ceilclip + 1
            if plan["MarkCeiling"]:
                mark_ceiling_columns += 1
                bands_ceiling += state.mark_ceiling(ceiling_handle, column,
                                                   ceilclip, floorclip_current, yl)
            yh = bottomfrac >> HEIGHTBITS
            if yh >= floorclip_current:
                yh = floorclip_current - 1
            if plan["MarkFloor"]:
                mark_floor_columns += 1
                bands_floor += state.mark_floor(floor_handle, column,
                                               ceilclip, floorclip_current, yh)
            if plan["MiddleTier"]:
                ceilingclip[column] = VIEWHEIGHT
                floorclip[column] = -1
            else:
                if plan["TopTier"]:
                    mid = pixhigh >> HEIGHTBITS
                    pixhigh = lowadd(pixhigh, plan["PixHighStep"])
                    if mid >= floorclip_current:
                        mid = floorclip_current - 1
                    if mid >= yl:
                        ceilingclip[column] = mid
                    else:
                        ceilingclip[column] = yl - 1
                elif plan["MarkCeiling"]:
                    ceilingclip[column] = yl - 1
                if plan["BottomTier"]:
                    mid = lowadd(pixlow, HEIGHTUNIT - 1) >> HEIGHTBITS
                    pixlow = lowadd(pixlow, plan["PixLowStep"])
                    if mid <= ceilclip:
                        mid = ceilclip + 1
                    if mid <= yh:
                        floorclip[column] = mid
                    else:
                        floorclip[column] = yh + 1
                elif plan["MarkFloor"]:
                    floorclip[column] = yh + 1
            scale = lowadd(scale, plan["ScaleStep"])
            topfrac = lowadd(topfrac, plan["TopStep"])
            bottomfrac = lowadd(bottomfrac, plan["BottomStep"])
        mark_ceiling_bands += bands_ceiling
        mark_floor_bands += bands_floor
        span_events.append({
            "Subsector": plan["Subsector"], "Seg": plan["Seg"],
            "FirstX": first, "LastX": last, "Kind": plan["Kind"],
            "CeilingCheck": 1 if plan["MarkCeiling"] else 0,
            "FloorCheck": 1 if plan["MarkFloor"] else 0,
            "CeilingBefore": ceiling_before, "CeilingAfter": ceiling_handle,
            "FloorBefore": floor_before, "FloorAfter": floor_handle,
            "CeilingMerge": ceiling_merges, "CeilingSplit": ceiling_splits,
            "FloorMerge": floor_merges, "FloorSplit": floor_splits,
            "CeilingBands": bands_ceiling, "FloorBands": bands_floor,
            "ProcessedColumns": last - first + 1, "EmittedRows": 0,
        })
    return {
        "state": state, "floor_plane": floor_plane, "ceiling_plane": ceiling_plane,
        "floor_eligible": floor_eligible, "ceiling_eligible": ceiling_eligible,
        "mark_ceiling_columns": mark_ceiling_columns,
        "mark_floor_columns": mark_floor_columns,
        "mark_ceiling_bands": mark_ceiling_bands,
        "mark_floor_bands": mark_floor_bands,
        "span_events": span_events,
    }


def plane_draw(scene, plans, projection, sine, yslope, distscale, zlight,
               coverage, captured, frame):
    """Independent r_plane.c R_DrawPlanes / r_draw.c R_DrawSpan full plane pass."""
    state = captured["state"]
    viewx = signed32(scene["view"][0])
    viewy = signed32(scene["view"][1])
    viewangle = unsigned32(scene["view"][2])
    viewz = signed32(scene["view"][3])
    basexscale, baseyscale = base_scales(viewangle, sine)
    inverse = projection["inverse"]
    records = state.records
    cachedheight = [0] * VIEWHEIGHT
    cacheddistance = [0] * VIEWHEIGHT
    cachedxstep = [0] * VIEWHEIGHT
    cachedystep = [0] * VIEWHEIGHT
    spanstart = [0] * VIEWHEIGHT
    spans = []
    plane_pixels = 0
    floor_pixels = 0
    ceiling_pixels = 0
    floor_visplanes = 0
    ceiling_visplanes = 0
    regular_visplanes = 0
    sky_visplanes = 0
    empty_visplanes = 0
    populated_visplanes = 0
    sky_bands = 0
    sky_pixels = 0
    row_cache_hits = 0
    row_cache_misses = 0
    colormap_texels = 0
    opened_rows = 0
    closed_rows = 0
    for index, record in enumerate(records):
        if record["MinX"] > record["MaxX"]:
            empty_visplanes += 1
            if record["Sky"]:
                sky_visplanes += 1
            else:
                regular_visplanes += 1
            continue
        if record["Sky"]:
            sky_visplanes += 1
            for x in range(record["MinX"], record["MaxX"] + 1):
                top = record["Top"][x + 1]
                bottom = record["Bottom"][x + 1]
                if top != 255 and top <= bottom:
                    sky_bands += 1
                    sky_pixels += bottom - top + 1
            continue
        regular_visplanes += 1
        if state.has_bands(index) == 0:
            empty_visplanes += 1
            continue
        populated_visplanes += 1
        height = record["Height"]
        planeheight = abs(signed32(height - viewz))
        lightrow = record["LightLevel"] >> LIGHTSEGSHIFT
        if lightrow >= LIGHTLEVELS:
            lightrow = LIGHTLEVELS - 1
        if lightrow < 0:
            lightrow = 0
        record["Top"][record["MaxX"] + 2] = 255
        record["Top"][record["MinX"]] = 255
        flat_pic = record["FlatPic"]
        flat_pixel = flat_pixel_by_index(flat_pic)
        plane_is_floor = signed32(height) < viewz
        if plane_is_floor:
            floor_visplanes += 1
        else:
            ceiling_visplanes += 1
        stop = record["MaxX"] + 1
        pixels_before = plane_pixels
        def map_plane(row, x1, x2):
            nonlocal plane_pixels, row_cache_hits, row_cache_misses, colormap_texels
            nonlocal closed_rows
            if planeheight != cachedheight[row]:
                cachedheight[row] = planeheight
                distance = fixed_mul(planeheight, yslope[row])
                cacheddistance[row] = distance
                xstep = fixed_mul(distance, basexscale)
                cachedxstep[row] = xstep
                ystep = fixed_mul(distance, baseyscale)
                cachedystep[row] = ystep
                cache = 0
                row_cache_misses += 1
            else:
                distance = cacheddistance[row]
                xstep = cachedxstep[row]
                ystep = cachedystep[row]
                cache = 1
                row_cache_hits += 1
            length = fixed_mul(distance, distscale[x1])
            angle = unsigned32(viewangle + inverse[x1]) >> ANGLETOFINESHIFT
            xfrac = lowadd(viewx, fixed_mul(cosine(sine, angle), length))
            yfrac = lowsub(lowneg(viewy), fixed_mul(sine[angle], length))
            start_xfrac = xfrac
            start_yfrac = yfrac
            distance_bin = signed32(distance) >> LIGHTZSHIFT
            if distance_bin >= MAXLIGHTZ or distance_bin < 0:
                distance_bin = MAXLIGHTZ - 1
            map_index = zlight[lightrow][distance_bin]
            mapped = colormap_value(flat_pixel, map_index)
            count = x2 - x1
            for step in range(count + 1):
                x = x1 + step
                offset = row * VIEWWIDTH + x
                if coverage[offset] != 0:
                    raise ValueError("plane pixel overlaps wall coverage at x=%d,y=%d" %
                                     (x, row))
                frame[offset] = mapped
                colormap_texels += 1
                plane_pixels += 1
                xfrac = lowadd(xfrac, xstep)
                yfrac = lowadd(yfrac, ystep)
            spans.append({
                "PlaneIndex": index, "Row": row, "FirstX": x1, "LastX": x2,
                "PlaneHeight": planeheight, "Distance": distance,
                "XStep": xstep, "YStep": ystep, "XFrac": start_xfrac,
                "YFrac": start_yfrac, "LightNum": lightrow, "MapIndex": map_index,
                "Pixels": count + 1, "CacheHit": cache,
            })
            closed_rows += 1
        for x in range(record["MinX"], stop + 1):
            padded_x = x + 1
            t1 = record["Top"][padded_x - 1]
            b1 = record["Bottom"][padded_x - 1]
            t2 = record["Top"][padded_x]
            b2 = record["Bottom"][padded_x]
            t1_current = t1
            b1_current = b1
            while t1_current < t2 and t1_current <= b1_current:
                start_x = spanstart[t1_current]
                map_plane(t1_current, start_x, x - 1)
                t1_current += 1
            while b1_current > b2 and b1_current >= t1_current:
                start_x = spanstart[b1_current]
                map_plane(b1_current, start_x, x - 1)
                b1_current -= 1
            while t2 < t1_current and t2 <= b2:
                spanstart[t2] = x
                opened_rows += 1
                t2 += 1
            while b2 > b1_current and b2 >= t2:
                spanstart[b2] = x
                opened_rows += 1
                b2 -= 1
        if plane_is_floor:
            floor_pixels += plane_pixels - pixels_before
        else:
            ceiling_pixels += plane_pixels - pixels_before
    return {
        "spans": spans, "plane_pixels": plane_pixels,
        "floor_pixels": floor_pixels, "ceiling_pixels": ceiling_pixels,
        "floor_visplanes": floor_visplanes, "ceiling_visplanes": ceiling_visplanes,
        "regular_visplanes": regular_visplanes, "sky_visplanes": sky_visplanes,
        "empty_visplanes": empty_visplanes, "populated_visplanes": populated_visplanes,
        "sky_bands": sky_bands, "sky_pixels": sky_pixels,
        "row_cache_hits": row_cache_hits, "row_cache_misses": row_cache_misses,
        "colormap_texels": colormap_texels,
        "opened_rows": opened_rows, "closed_rows": closed_rows,
    }


def plane_sample_params(yslope, distscale, inverse, sine, viewx, viewy, viewangle,
                        planeheight, row, firstx, lightrow):
    if planeheight != 0:
        distance = fixed_mul(planeheight, yslope[row])
    else:
        distance = 0
    xstep = fixed_mul(distance, base_scales(viewangle, sine)[0])
    ystep = fixed_mul(distance, base_scales(viewangle, sine)[1])
    length = fixed_mul(distance, distscale[firstx])
    angle = unsigned32(viewangle + inverse[firstx]) >> ANGLETOFINESHIFT
    xfrac = lowadd(viewx, fixed_mul(cosine(sine, angle), length))
    yfrac = lowsub(lowneg(viewy), fixed_mul(sine[angle], length))
    return distance, xstep, ystep, xfrac, yfrac


def spot_value(xfrac, yfrac):
    return ((yfrac >> 10) & (63 * 64)) + ((xfrac >> 16) & 63)


def build_scene_data(name, scene, tables, base, textured):
    tangent, sine, tant = tables
    data = textured.build_scene(scene, tables, base)
    focal, pre, post, inverse, kind, clip = base.build_projection(tangent)
    projection = {"focal": focal, "pre": pre, "post": post, "inverse": inverse,
                  "kind": kind, "clip": clip}
    yslope = yslope_table()
    distscale = distscale_table(projection["inverse"], sine)
    zlight = zlight_table()
    coverage, wall_ranges, wall_ceil, wall_floor = wall_clip_coverage(scene, data["plans"])
    captured = plane_capture(scene, data["plans"])
    frame = list(data["frame"])
    plane = plane_draw(scene, data["plans"], projection, sine, yslope, distscale,
                       zlight, coverage, captured, frame)
    wall_drawn = data["counters"]["drawn_pixels"]
    covered = sum(coverage)
    if covered != wall_drawn:
        raise ValueError("wall coverage %d vs drawn %d" % (covered, wall_drawn))
    fallback_zero = 0
    nonzero = 0
    for byte in frame:
        if byte != 0:
            nonzero += 1
        else:
            fallback_zero += 1
    hash_value = FNV_OFFSET
    for byte in frame:
        hash_value = ((hash_value ^ (byte & 255)) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return {
        "scene": scene, "spans": data["spans"], "plans": data["plans"],
        "wall_frame": data["frame"], "wall_counters": data["counters"],
        "frame": frame, "plane": plane, "captured": captured,
        "coverage": coverage, "covered": covered, "wall_drawn": wall_drawn,
        "nonzero": nonzero, "zero": fallback_zero, "hash": hash_value,
        "yslope": yslope, "distscale": distscale, "zlight": zlight,
        "projection": projection,
    }


