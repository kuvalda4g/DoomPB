import argparse
import os
import re
import struct
import sys

FNV_OFFSET = 0xcbf29ce484222325
FNV_PRIME = 0x100000001b3
FNV_MASK = 0xffffffffffffffff

ARRAYS = [
    # name, count, first, last, full little-endian FNV-1a64
    ("finetangent", 4096, -170910304, 170910304, "6E300CFD277525E1"),
    ("finesine", 10240, 25, 65535, "ADD266F0CB7B06B6"),
    ("tantoangle", 2049, 0, 536870912, "56213612F87A0F4A"),
]


def parse_c_array(text, name):
    match = re.search(r"\b" + name + r"\[(?:[^\]]*)\]\s*=\s*\{", text)
    if match is None:
        raise ValueError("array %s not found in source" % name)
    start = text.index("{", match.start())
    end = text.index("};", start)
    body = text[start + 1:end]
    tokens = [token.strip() for token in body.replace("\n", " ").split(",")]
    return [int(token) for token in tokens if token]


def fnv_le32(values):
    digest = FNV_OFFSET
    for value in values:
        low = value & 0xFFFFFFFF
        for byte in struct.pack("<I", low):
            digest ^= byte
            digest = (digest * FNV_PRIME) & FNV_MASK
    return digest


def default_source():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)
    return os.path.join(repo_root, "..", "doom-original", "linuxdoom-1.10", "tables.c")


def main():
    parser = argparse.ArgumentParser(description="Generate DoomPB trig tables from pinned tables.c")
    parser.add_argument("--source", default=default_source(), help="path to pinned tables.c")
    parser.add_argument("--output", default="", help="output .pbi path (default: repository src/Core)")
    args = parser.parse_args()

    source_path = os.path.abspath(args.source)
    if not os.path.isfile(source_path):
        print("error: pinned tables.c not found at %s" % source_path, file=sys.stderr)
        return 1

    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)
    output_path = os.path.abspath(args.output) if args.output else os.path.join(repo_root, "src", "Core", "TrigTablesData.pbi")

    with open(source_path, "r", encoding="latin-1") as handle:
        text = handle.read()

    tables = []
    for name, count, first, last, expected_hash in ARRAYS:
        values = parse_c_array(text, name)
        observed_hash = fnv_le32(values)
        observed_hex = "%016X" % observed_hash
        problems = []
        if len(values) != count:
            problems.append("count %d != expected %d" % (len(values), count))
        if values[0] != first:
            problems.append("first %d != expected %d" % (values[0], first))
        if values[-1] != last:
            problems.append("last %d != expected %d" % (values[-1], last))
        if observed_hex != expected_hash:
            problems.append("hash %s != expected %s" % (observed_hex, expected_hash))
        if problems:
            print("error: %s table does not match the pinned reference: %s" % (name, "; ".join(problems)), file=sys.stderr)
            print("error: investigate extraction/order/source revision instead of changing expectations.", file=sys.stderr)
            return 1
        print("%s: count %d, FNV-1a64 LE32 %s" % (name, count, observed_hex))
        tables.append((name, values, observed_hex))

    labels = {
        "finetangent": "DoomPBTrigFinetangentData",
        "finesine": "DoomPBTrigSineData",
        "tantoangle": "DoomPBTrigTanToAngleData",
    }

    lines = []
    lines.append("; -----------------------------------------------------------------------------")
    lines.append("; DoomPB - generated exact trig lookup tables from pinned Linux Doom 1.10")
    lines.append("; Copyright (C) 2026 DoomPB contributors")
    lines.append("; SPDX-License-Identifier: GPL-2.0-only")
    lines.append(";")
    lines.append("; Original table algorithms copyright (C) 1993-1996 by id Software, Inc.")
    lines.append("; Provenance: ../doom-original/linuxdoom-1.10/tables.c, upstream commit")
    lines.append(";   a77dfb96cb91780ca334d0d4cfd86957558007e0.")
    lines.append(";")
    lines.append("; This file is generated by scripts/gen_trig_tables.py. Do not hand-edit.")
    lines.append("; The generator validates length/first/last and the full little-endian")
    lines.append("; FNV-1a64 hash of every array against the pinned reference.")
    lines.append(";")
    for name, values, digest in tables:
        lines.append("; %s[%d]: %s (low 32 bits, little-endian, two's complement)" % (name, len(values), digest))
    lines.append("; Data.l values are 32-bit signed literals; tantoangle raw values stay")
    lines.append("; within the signed-positive range and are read as raw BAM bit patterns.")
    lines.append("; -----------------------------------------------------------------------------")
    lines.append("")
    lines.append("DataSection")
    for name, values, digest in tables:
        lines.append("  %s:" % labels[name])
        for offset in range(0, len(values), 8):
            chunk = values[offset:offset + 8]
            lines.append("  Data.l " + ", ".join(str(value) for value in chunk))
    lines.append("EndDataSection")
    lines.append("")

    with open(output_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))

    print("wrote %s" % output_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
