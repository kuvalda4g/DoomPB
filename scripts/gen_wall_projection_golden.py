"""
DoomPB - independent M3-05 wall projection/frame golden fixture generator.

Provenance: reads only numeric arrays from the pinned
../doom-original/linuxdoom-1.10/tables.c (commit
a77dfb96cb91780ca334d0d4cfd86957558007e0): finetangent[4096],
finesine[10240] and tantoangle[2049]. It implements a separate pure-integer
Python oracle for:
  - r_main.c R_InitTextureMapping, R_PointToAngle, R_PointToDist,
    R_ScaleFromGlobalAngle;
  - r_segs.c R_AddLine relevant projection/backface/FOV, R_StoreWallRange
    distance/scale/heights/12-bit interpolation and R_RenderSegLoop solid-color
    M3-05 subset;
  - r_bsp.c R_Subsector source-seg ??chronology plus an idealized solidsegs
    coverage bitmap for the synthetic zero-node scenes.

The four small synthetic scenes and their four numeric sample column sets are
encoded below and mirrored by the PB test builders. Expected span records, plan
fields, sample palette rows and FNV-1a64 frame hashes are generated by this
oracle, never from DoomPB's new renderer output. The committed fixture is
numeric/synthetic only: no WAD bytes, game graphics, copyrighted resource
payload or screenshots. Regeneration is deterministic; do not hand-edit.

Production and tests never execute Python. The oracle uses pinned original
integer formulas with the documented M3-05 signed-overflow low-32 wrap policy
for the same edge spots as WallProject.pbi; ordinary scene values stay exact.
"""
