def scene_build(scene, tables):
    tangent, sine, tant = tables
    focal, pre, post, inverse, kind, clip = build_projection(tangent)
    projection = {"focal": focal, "post": post, "inverse": inverse, "clip": clip}
    scene = dict(scene)
    scene["tant"] = tant
    spans = visible_spans(scene, projection)
    plans = [span_plan(scene, span, projection, sine, tant) for span in spans]
    frame = draw_frame(plans)
    hash_value = frame_hash(frame)
    samples = []
    for x in scene["samples"]:
        samples.append([frame[row * VIEWWIDTH + x]
                        for row in range(VIEWHEIGHT)])
    return {
        "spans": spans,
        "plans": plans,
        "hash": hash_value,
        "frame": frame,
        "samplex": scene["samples"],
        "sample_rows": samples,
    }


