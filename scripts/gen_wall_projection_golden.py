def unsigned32(value):
    return value & MASK32


def signed32(value):
    low = value & MASK32
    if low >= SIGN32:
        return low - (1 << 32)
    return low


def lowadd(a, b):
    return signed32(unsigned32(a) + unsigned32(b))


def lowsub(a, b):
    return signed32(unsigned32(a) - unsigned32(b))


def lowneg(a):
    return signed32(-unsigned32(a))


def trunc_div(numerator, denominator):
    if numerator == 0:
        return 0
    magnitude = abs(numerator) // abs(denominator)
    if (numerator < 0) != (denominator < 0):
        return -magnitude
    return magnitude


def parse_c_array(text, name):
    match = re.search(r"\b" + re.escape(name) + r"\[(?:[^\]]*)\]\s*=\s*\{", text)
    if match is None:
        raise ValueError("array %s not found" % name)
    start = text.index("{", match.start())
    end = text.index("};", start)
    tokens = [token.strip() for token in text[start + 1:end].replace("\n", " ").split(",")]
    return [int(token) for token in tokens if token]


def load_tables(source_path):
    with open(source_path, "r", encoding="latin-1") as handle:
        text = handle.read()
    tangent = parse_c_array(text, "finetangent")
    sine = parse_c_array(text, "finesine")
    tant = parse_c_array(text, "tantoangle")
    if len(tangent) != 4096 or tangent[0] != -170910304 or tangent[-1] != 170910304:
        raise ValueError("finetangent table does not match the pinned shape")
    if len(sine) != 10240 or sine[0] != 25 or sine[2048] != 65535:
        raise ValueError("finesine table does not match the pinned shape")
    if len(tant) != 2049 or tant[0] != 0:
        raise ValueError("tantoangle table does not match the pinned shape")
    return tangent, sine, tant


def fixed_mul(a, b):
    return signed32(signed32(a) * signed32(b) >> FRACBITS)


def fixed_div(a, b):
    a = signed32(a)
    b = signed32(b)
    magnitude_a = abs(a)
    magnitude_b = abs(b)
    if (magnitude_a >> 14) >= magnitude_b:
        return INT32_MIN if (a < 0) != (b < 0) else INT32_MAX
    return signed32(trunc_div(a * FRACUNIT, b))


def fence(tangent_value):
    if tangent_value > FRACUNIT * 2:
        return -1, 1
    if tangent_value < -FRACUNIT * 2:
        return VIEWWIDTH + 1, 2
    return 0, 0


def build_projection(tangent):
    focal = fixed_div(CENTERXFIXED, tangent[FOCAL_INDEX])
    pre = []
    kind = []
    for value in tangent:
        fenced, fence_kind = fence(value)
        kind.append(fence_kind)
        if fence_kind:
            pre.append(fenced)
            continue
        scaled = fixed_mul(value, focal)
        member = CENTERXFIXED - scaled + FRACUNIT - 1
        t = signed32(member >> FRACBITS)
        t = max(-1, min(VIEWWIDTH + 1, t))
        pre.append(t)
    inverse = []
    for x in range(VIEWWIDTH + 1):
        index = 0
        while index < len(pre) and pre[index] > x:
            index += 1
        if index >= len(pre):
            raise ValueError("viewangletox did not cross column %d" % x)
        inverse.append(unsigned32((index << ANGLETOFINESHIFT) - ANG90))
    post = [0 if v == -1 else VIEWWIDTH if v == VIEWWIDTH + 1 else v for v in pre]
    return focal, pre, post, inverse, kind, inverse[0]


def slope_div(num, den):
    num = unsigned32(num)
    den = unsigned32(den)
    if den < 512:
        return SLOPERANGE
    answer = unsigned32(num << 3) // (den >> 8)
    return answer if answer <= SLOPERANGE else SLOPERANGE


def point_to_angle(viewx, viewy, x, y, tant):
    dx = signed32(x - viewx) if -(1 << 31) <= x - viewx <= (1 << 31) - 1 else unsigned32(x - viewx)
    dy = signed32(y - viewy) if -(1 << 31) <= y - viewy <= (1 << 31) - 1 else unsigned32(y - viewy)
    if dx == 0 and dy == 0:
        return 0
    lowered = dx >= 0
    raised = dy >= 0
    magx = -dx if dx < 0 else dx
    magy = -dy if dy < 0 else dy
    if magx > magy:
        slope = slope_div(magy, magx)
    else:
        slope = slope_div(magx, magy)
    atan = unsigned32(tant[slope])
    if lowered:
        if raised:
            if magx > magy:
                raw = atan
            else:
                raw = unsigned32((ANG90 - 1) - atan)
        else:
            if magx > magy:
                raw = unsigned32(-atan)
            else:
                raw = unsigned32(ANG270 + atan)
    else:
        if raised:
            if magx > magy:
                raw = unsigned32((ANG180 - 1) - atan)
            else:
                raw = unsigned32(ANG90 + atan)
        else:
            if magx > magy:
                raw = unsigned32(ANG180 + atan)
            else:
                raw = unsigned32((ANG270 - 1) - atan)
    return raw


def point_to_dist(viewx, viewy, x, y, sine, tant):
    dx = x - viewx
    dy = y - viewy
    if not (-(1 << 31) <= dx <= (1 << 31) - 1) or not (-(1 << 31) <= dy <= (1 << 31) - 1):
        raise ValueError("point-to-dist signed delta overflow")
    dx = abs(dx)
    dy = abs(dy)
    if dy > dx:
        dx, dy = dy, dx
    if dx == 0:
        raise ValueError("zero point-to-dist denominator")
    ratio = fixed_div(dy, dx)
    slope = ratio >> DBITS
    if slope < 0 or slope > SLOPERANGE:
        raise ValueError("point-to-dist slope out of domain")
    atan = signed32(tant[slope])
    fine = unsigned32((unsigned32(atan) + ANG90) >> ANGLETOFINESHIFT) & FINEMASK
    cosv = sine[fine]
    if cosv <= 0:
        raise ValueError("point-to-dist cosine is nonpositive")
    return fixed_div(dx, cosv)


def scale_from_sines(projection, distance, sine_a, sine_b):
    num = fixed_mul(projection, sine_b)
    num_high = num >> FRACBITS
    den = fixed_mul(distance, sine_a)
    if den > num_high:
        scale = fixed_div(num, den)
        if scale > SCALE_MAX:
            scale = SCALE_MAX
        elif scale < SCALE_MIN:
            scale = SCALE_MIN
    else:
        scale = SCALE_MAX
    return scale


def signed_sine_index(raw, sine):
    raw = unsigned32(raw)
    if raw > 0x7FFFFFFF:
        raise ValueError("negative signed finesine index")
    index = raw >> ANGLETOFINESHIFT
    if index < 0 or index > len(sine) - 1:
        raise ValueError("finesine index out of domain")
    return index, sine[index]


def scale_global(viewangle, visangle, normalangle, distance, projection, sine):
    anglea = unsigned32(ANG90 + unsigned32(visangle - viewangle))
    angleb = unsigned32(ANG90 + unsigned32(visangle - normalangle))
    index_a, sine_a = signed_sine_index(anglea, sine)
    index_b, sine_b = signed_sine_index(angleb, sine)
    return scale_from_sines(projection, distance, sine_a, sine_b), index_a, index_b


def seg_raw_to_bam(raw16):
    return unsigned32((unsigned32(raw16) & 0xFFFF) << FRACBITS)


def offset_angle(normalangle, referenceangle):
    delta = unsigned32(normalangle - referenceangle)
    if delta == 0x80000000:
        raise ValueError("abs INT32_MIN undefined separation")
    magnitude = delta if delta < 0x80000000 else (1 << 32) - delta
    offset = ANG90 if magnitude > ANG90 else magnitude
    return magnitude, offset


def distance_angle(offset):
    clamped = ANG90 if offset > ANG90 else offset
    distangle = unsigned32(ANG90 - clamped)
    index = distangle >> ANGLETOFINESHIFT
    return clamped, distangle, index


def scale_step_calc(first, last, scale1, scale2):
    if last == first:
        return scale1, 0
    difference = scale2 - scale1
    if difference < INT32_MIN or difference > INT32_MAX:
        raise ValueError("scale difference signed overflow")
    return scale2, trunc_div(difference, last - first)


def apply_left_clip(rel, span, clip):
    two = unsigned32(clip + clip)
    tspan = unsigned32(rel + clip)
    if tspan > two:
        tspan = unsigned32(tspan - two)
        if tspan >= span:
            return None
        return clip
    return rel


def apply_right_clip(rel, span, clip):
    two = unsigned32(clip + clip)
    tspan = unsigned32(clip - rel)
    if tspan > two:
        tspan = unsigned32(tspan - two)
        if tspan >= span:
            return None
        return unsigned32(-clip)
    return rel


def slot_present(name):
    if name == "-" or name == "" or name is None:
        return 0
    return 1


